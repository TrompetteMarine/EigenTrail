//! Independent reconstruction of dated root, normalisation and inverse proofs.
use eigentrail_core::{
    Eigensystem, Error, Matrix, Result,
    resources::{Cancellation, memory, memory::HeapBytes},
    rolling_lineage::{
        Lens, Request, Slot,
        report::{DateEvidence, FrameProof, FrameState, InverseState, Reason, Reference},
    },
    scalar::{self, Interval, interval, point},
};

#[derive(Clone, Copy)]
pub struct CheckedReference<'a> {
    pub midpoint: &'a Matrix,
    pub eigensystem: &'a Eigensystem,
    pub matrix_error: f64,
    pub numerical_rho: f64,
}

pub struct VerifiedDate<'a> {
    pub subject: usize,
    pub date: usize,
    pub root: CheckedReference<'a>,
    pub correlation: Option<CheckedReference<'a>>,
    pub normalised_precision: Option<CheckedReference<'a>>,
}

impl HeapBytes for VerifiedDate<'_> {
    fn heap_bytes(&self) -> Result<usize> {
        Ok(0)
    }
}

impl<'a> VerifiedDate<'a> {
    pub fn reference(&self, reference: Reference) -> Option<CheckedReference<'a>> {
        match reference {
            Reference::Root => Some(self.root),
            Reference::Correlation => self.correlation,
            Reference::NormalisedPrecision => self.normalised_precision,
        }
    }
}

fn invalid(message: &str) -> Error {
    memory::text(message)
        .map(Error::Invalid)
        .unwrap_or_else(|error| error)
}
fn nonnegative(value: f64) -> Result<()> {
    if value.is_finite() && value >= 0. {
        Ok(())
    } else {
        Err(invalid(
            "checker rolling: finite nonnegative bound required",
        ))
    }
}
fn finite(value: Interval) -> Result<Interval> {
    if value.is_empty() || !value.inf().is_finite() || !value.sup().is_finite() {
        Err(invalid("checker rolling: nonfinite proof enclosure"))
    } else {
        Ok(value)
    }
}

fn matrix(matrix: &Matrix, n: usize, cancel: &Cancellation) -> Result<()> {
    cancel.poll()?;
    if !(1..=256).contains(&n) || matrix.n != n || n.checked_mul(n) != Some(matrix.data.len()) {
        return Err(invalid("checker rolling: matrix dimensions differ"));
    }
    for column in 0..n {
        cancel.poll()?;
        for row in 0..n {
            if !matrix.at(row, column).is_finite()
                || row < column && matrix.at(row, column) != matrix.at(column, row)
            {
                return Err(invalid(
                    "checker rolling: finite exactly symmetric matrix required",
                ));
            }
        }
    }
    Ok(())
}

fn alignment(eigensystem: &Eigensystem, matrix_error: f64) -> Result<f64> {
    nonnegative(matrix_error)?;
    nonnegative(eigensystem.backward)?;
    let Some(&minimum) = eigensystem.values.last() else {
        return Err(invalid("checker rolling: missing reference spectrum"));
    };
    let uncertainty = finite(point(eigensystem.backward) + point(matrix_error))?;
    let floor = finite(point(minimum) - point(uncertainty.sup()))?;
    if minimum <= 0. || floor.inf() <= 0. {
        return Err(invalid(
            "checker rolling: reference strict positive floor not proved",
        ));
    }
    if uncertainty.sup() == 0. {
        return Ok(0.);
    }
    Ok(finite(scalar::ln(point(minimum))? - scalar::ln(floor)?)?.sup())
}

fn check_reference<'a>(
    proof: &'a FrameProof,
    required_error: f64,
    cancel: &Cancellation,
) -> Result<CheckedReference<'a>> {
    nonnegative(proof.matrix_error)?;
    nonnegative(proof.numerical_rho)?;
    if proof.matrix_error < required_error {
        return Err(invalid("checker rolling: understated normalisation error"));
    }
    crate::eigensystem::inspect(&proof.midpoint, &proof.eigensystem, cancel)?;
    if proof.numerical_rho < alignment(&proof.eigensystem, proof.matrix_error)? {
        return Err(invalid(
            "checker rolling: understated numerical alignment radius",
        ));
    }
    Ok(CheckedReference {
        midpoint: &proof.midpoint,
        eigensystem: &proof.eigensystem,
        matrix_error: proof.matrix_error,
        numerical_rho: proof.numerical_rho,
    })
}

/// Target entries are independent enclosures of the exact SPD input being
/// normalised. The supplied midpoint is charged, not regenerated by an EVD.
fn normalisation_error(
    midpoint: &Matrix,
    n: usize,
    entry: impl Fn(usize, usize) -> Interval,
    cancel: &Cancellation,
) -> Result<f64> {
    memory::scope(|| {
        matrix(midpoint, n, cancel)?;
        let mut diagonal_roots = memory::capacity(n)?;
        for index in 0..n {
            cancel.poll()?;
            let value = finite(entry(index, index))?;
            if value.inf() <= 0. {
                return Err(invalid(
                    "checker rolling: normalisation denominator not positive",
                ));
            }
            diagonal_roots.push(value.sqrt());
        }
        let mut squared_error = point(0.);
        for column in 0..n {
            cancel.poll()?;
            squared_error += scalar::square(point(1.) - point(midpoint.at(column, column)));
            for row in 0..column {
                let normalised =
                    finite(entry(row, column) / diagonal_roots[row] / diagonal_roots[column])?;
                let difference = normalised - point(midpoint.at(row, column));
                squared_error += point(2.) * scalar::square(difference);
            }
        }
        Ok(finite(squared_error.sqrt())?.sup())
    })
}

fn inverse_error(
    root: CheckedReference<'_>,
    inverse: &Matrix,
    cancel: &Cancellation,
) -> Result<f64> {
    let n = root.midpoint.n;
    matrix(inverse, n, cancel)?;
    let minimum = root.eigensystem.values[n - 1];
    let floor = (point(minimum) - point(root.eigensystem.backward)).inf();
    if floor <= 0. {
        return Err(invalid("checker rolling: inverse root floor unresolved"));
    }
    let mut squared = point(0.);
    for column in 0..n {
        cancel.poll()?;
        for row in 0..n {
            let mut reconstructed = point(0.);
            for index in 0..n {
                reconstructed +=
                    point(root.midpoint.at(row, index)) * point(inverse.at(index, column));
            }
            squared += scalar::square(point(f64::from(row == column)) - reconstructed);
        }
    }
    Ok(finite(squared.sqrt() / point(floor))?.sup())
}

fn unavailable(reason: Reason) -> Result<()> {
    if reason != Reason::NormalisationUnresolved {
        return Err(invalid(
            "checker rolling: unsupported frame-unavailable reason",
        ));
    }
    Ok(())
}

/// Checks reported witnesses directly. It never calls the producer's frame,
/// regional, view-assembly or rolling decision routines.
pub fn inspect_date<'a>(
    request: &'a Request,
    evidence: &'a DateEvidence,
    cancel: &Cancellation,
) -> Result<VerifiedDate<'a>> {
    memory::scope(|| {
        cancel.poll()?;
        if evidence.date >= request.dates.len() {
            return Err(invalid("checker rolling: unknown dated evidence"));
        }
        let slot = request
            .subjects
            .get(evidence.subject)
            .and_then(|person| person.slots.get(evidence.date))
            .ok_or_else(|| invalid("checker rolling: unknown subject/date evidence"))?;
        let Slot::Observed { covariance } = slot else {
            return Err(invalid(
                "checker rolling: missing slot has numerical evidence",
            ));
        };
        let n = request.features.len();
        matrix(covariance, n, cancel)?;
        nonnegative(evidence.root_numerical_rho)?;
        for index in 0..n {
            cancel.poll()?;
            if covariance.at(index, index) <= 0. {
                return Err(invalid("checker rolling: nonpositive root variance"));
            }
        }
        crate::eigensystem::inspect(covariance, &evidence.root, cancel)?;
        if evidence.root_numerical_rho < alignment(&evidence.root, 0.)? {
            return Err(invalid(
                "checker rolling: root numerical radius understated",
            ));
        }
        let root = CheckedReference {
            midpoint: covariance,
            eigensystem: &evidence.root,
            matrix_error: 0.,
            numerical_rho: evidence.root_numerical_rho,
        };
        let need_c = request.lenses.contains(&Lens::Correlation)
            || n <= 2 && request.lenses.contains(&Lens::Partial);
        let correlation = match (&evidence.correlation, need_c) {
            (FrameState::NotRequested, false) => None,
            (FrameState::Unavailable { reason }, true) => {
                unavailable(*reason)?;
                None
            }
            (FrameState::Available { proof }, true) => {
                let error = normalisation_error(
                    &proof.midpoint,
                    n,
                    |row, column| point(covariance.at(row, column)),
                    cancel,
                )?;
                Some(check_reference(proof, error, cancel)?)
            }
            _ => {
                return Err(invalid(
                    "checker rolling: correlation evidence does not match requested views",
                ));
            }
        };
        let need_q = n > 2 && request.lenses.contains(&Lens::Partial);
        let normalised_precision = match (&evidence.inverse, &evidence.normalised_precision, need_q)
        {
            (InverseState::NotRequested, FrameState::NotRequested, false) => None,
            (
                InverseState::Unavailable { reason: first },
                FrameState::Unavailable { reason: second },
                true,
            ) => {
                unavailable(*first)?;
                unavailable(*second)?;
                None
            }
            (
                InverseState::Available {
                    midpoint,
                    operator_error,
                },
                FrameState::Available { proof },
                true,
            ) => {
                nonnegative(*operator_error)?;
                let required = inverse_error(root, midpoint, cancel)?;
                if *operator_error < required {
                    return Err(invalid(
                        "checker rolling: inverse residual allowance understated",
                    ));
                }
                let error_band = interval(-*operator_error, *operator_error)?;
                let error = normalisation_error(
                    &proof.midpoint,
                    n,
                    |row, column| point(midpoint.at(row, column)) + error_band,
                    cancel,
                )?;
                Some(check_reference(proof, error, cancel)?)
            }
            _ => {
                return Err(invalid(
                    "checker rolling: inverse/Q evidence does not match requested views",
                ));
            }
        };
        cancel.poll()?;
        Ok(VerifiedDate {
            subject: evidence.subject,
            date: evidence.date,
            root,
            correlation,
            normalised_precision,
        })
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use eigentrail_core::rolling_lineage::{self as rolling, views as producer};
    use serde_json::json;

    fn request(n: usize, data: Vec<f64>, rho: Option<f64>) -> Request {
        let uncertainty = match rho {
            Some(rho) => {
                json!({"mode":"conditional","rho":rho,"joint_event":"supplied-event","provider":"not-a-sampling-level"})
            }
            None => json!({"mode":"point"}),
        };
        serde_json::from_value(json!({
            "schema":rolling::SCHEMA,"chart":{"frame":"synthetic-checker-chart","coordinates":"frame_coefficients"},
            "features":(0..n).map(|i|json!({"id":format!("feature{i}"),"unit":"one"})).collect::<Vec<_>>(),
            "dates":[{"id":"date0","time":0.}],"subjects":[{"id":"subject0","slots":[{"tag":"observed","covariance":{"n":n,"data":data}}]}],
            "lenses":["covariance","precision","correlation","partial"],
            "representation":{"symmetry":"exact","correction":{"kind":"none"}},"grouping":{"rtol":1e-12},
            "tolerance_deg":20.,"uncertainty":uncertainty,
            "scope":{"lens_travel":[],"rank_masks":[
                {"lens":"covariance","ranks":[[0,n]]},{"lens":"precision","ranks":[[0,n]]},
                {"lens":"correlation","ranks":[[0,n]]},{"lens":"partial","ranks":[[0,n]]}],
                "max_lag":1,"missing":"skip_recorded","policy":"draft_f_conservative","certificate":"observed_dated_subspaces","direct_scope":"all_later_slots"},
            "founders":[],"projection":{"kind":"counts"},"limits":{"max_candidates":10000,"max_edge_records":10000,"max_bytes":536870912,"chunk_records":64},
            "precision":{"format":"binary64","angle_unit":"degrees"}
        })).unwrap()
    }

    #[test]
    fn independent_reconstruction_matches_point_planar_general_and_unsupported_views() {
        let inputs = [
            request(2, vec![4., 0., 0., 1.], None),
            request(2, vec![1., 0.5, 0.5, 1.], Some(0.1)),
            request(3, vec![1., 0.8, 0., 0.8, 1., 0.5, 0., 0.5, 1.], None),
            request(3, vec![1., 0.8, 0., 0.8, 1., 0.5, 0., 0.5, 1.], Some(1.)),
            request(1, vec![2.], None),
        ];
        let cancel = Cancellation::default();
        for input in inputs {
            rolling::validate_structure(&input, &cancel).unwrap();
            let produced = producer::prepare_date(&input, 0, 0, 7, &cancel)
                .unwrap()
                .unwrap();
            let checked = inspect_date(&input, &produced.evidence, &cancel).unwrap();
            let expected =
                super::super::views::reconstruct_date(&input, &checked, 7, &cancel).unwrap();
            assert_eq!(produced.views, expected);
        }
    }

    #[test]
    fn forged_root_normalisation_inverse_and_alignment_are_rejected() {
        let input = request(3, vec![4., 1., 1., 1., 2., 0., 1., 0., 3.], None);
        let cancel = Cancellation::default();
        let produced = producer::prepare_date(&input, 0, 0, 0, &cancel)
            .unwrap()
            .unwrap();
        inspect_date(&input, &produced.evidence, &cancel).unwrap();
        for attack in 0..9 {
            let mut evidence = produced.evidence.clone();
            match attack {
                0 => evidence.root.values[0] += 1.,
                1 => evidence.root.vectors.data[0] += 0.1,
                2 => evidence.root_numerical_rho = 0.,
                3 => {
                    if let FrameState::Available { proof } = &mut evidence.correlation {
                        proof.matrix_error = 0.;
                    }
                }
                4 => {
                    if let FrameState::Available { proof } = &mut evidence.correlation {
                        proof.numerical_rho = 0.;
                    }
                }
                5 => {
                    if let InverseState::Available { operator_error, .. } = &mut evidence.inverse {
                        *operator_error = 0.;
                    }
                }
                6 => {
                    if let InverseState::Available { midpoint, .. } = &mut evidence.inverse {
                        midpoint.data[0] += 0.1;
                    }
                }
                7 => {
                    if let FrameState::Available { proof } = &mut evidence.normalised_precision {
                        proof.matrix_error = 0.;
                    }
                }
                8 => {
                    if let FrameState::Available { proof } = &mut evidence.normalised_precision {
                        proof.midpoint.data[1] += 0.1;
                    }
                }
                _ => unreachable!(),
            }
            assert!(
                inspect_date(&input, &evidence, &cancel).is_err(),
                "attack {attack} accepted"
            );
        }
        let mut wrong_date = produced.evidence.clone();
        wrong_date.date = 1;
        assert!(inspect_date(&input, &wrong_date, &cancel).is_err());
        let mut wrong_subject = produced.evidence.clone();
        wrong_subject.subject = 1;
        assert!(inspect_date(&input, &wrong_subject, &cancel).is_err());
    }

    #[test]
    fn requested_frame_shape_missing_slot_cancellation_and_resources_are_checked() {
        let mut input = request(2, vec![1., 0.5, 0.5, 1.], Some(0.1));
        let cancel = Cancellation::default();
        let produced = producer::prepare_date(&input, 0, 0, 0, &cancel)
            .unwrap()
            .unwrap();
        let mut absent = produced.evidence.clone();
        absent.correlation = FrameState::NotRequested;
        assert!(inspect_date(&input, &absent, &cancel).is_err());
        let operation = memory::Operation::new(8192).unwrap();
        assert!(matches!(
            operation.run(|| inspect_date(&input, &produced.evidence, &cancel)),
            Err(Error::Resource(_))
        ));
        input.subjects[0].slots[0] = Slot::Missing {
            reason: "not observed".into(),
        };
        assert!(inspect_date(&input, &produced.evidence, &cancel).is_err());
        cancel.cancel();
        assert!(matches!(
            inspect_date(&input, &produced.evidence, &cancel),
            Err(Error::Cancelled)
        ));
    }
}
